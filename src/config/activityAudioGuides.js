/**
 * Helper to get activity audio guide with guaranteed steps and expert tips
 */
export const getActivityAudioGuide = (activityId, fallbackTitle = '') => {
  const guide =
    activityId && ACTIVITY_AUDIO_GUIDES[activityId]
      ? { ...ACTIVITY_AUDIO_GUIDES[activityId], id: activityId }
      : {
          id: activityId || 'activity',
          title: fallbackTitle || 'النشاط التفاعلي',
          tag: 'إرشادات النشاط',
          icon: '🎯',
          goal: 'التركيز والتفاعل البصري وإكمال خطوات النشاط بنجاح.',
          audioScript: `أهلاً يا بطل في نشاط ${fallbackTitle || 'هذا النشاط'}! انظر إلى الشاشة بتركيز، واتبع الإرشادات وتفاعل مع العناصر لتحصل على النقاط والنجوم وتنهي المهمة بنجاح!`,
        };

  // Ensure steps are always richly provided
  if (!guide.steps || !Array.isArray(guide.steps) || guide.steps.length === 0) {
    guide.steps = [
      {
        number: 1,
        title: 'انظر بتركيز وهدوء',
        desc: 'راقب الشاشة وتتبع العنصر أو الصديق باهتمام ونظرة دافئة.',
        icon: '👀',
      },
      {
        number: 2,
        title: 'تفاعل في دورك',
        desc: guide.goal ? guide.goal : 'اضغط على العنصر التفاعلي المطلوب في اللحظة المناسبة.',
        icon: '👆',
      },
      {
        number: 3,
        title: 'احصد النجوم والتشجيع',
        desc: 'اجمع النجوم واحتفل بإنجاز المهمة مع سماع صوت التصفيق والمديح.',
        icon: '⭐',
      },
    ];
  }

  // Ensure expert guidance tip is always provided
  if (!guide.tip) {
    guide.tip = 'نصيحة للأهل والمدرب: امنح الطفل وقتاً كافياً للاستكشاف البصري دون استعجال، وشاركه النظرة والابتسامة عند التفاعل.';
  }

  return guide;
};
